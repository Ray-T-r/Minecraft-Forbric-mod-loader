	@Test
	void theBuilderPassesTheOwnerRestoresTheBlockAndItsOutputVerifiesAndRuns(@TempDir Path directory) throws Exception {
		// Single-class game jars, real runtime jars: what the builder decides from what the families' jars contain,
		// with the production context reading the hook's event and finding no NeoForge-side counterpart for it.
		Path vanilla = jar(directory, "vanilla.jar", Map.of(OWNER, gameClass(vanilla("vanillaJoin"), "vanillaJoin")));
		Path neo = jar(directory, "neo.jar", Map.of(OWNER, gameClass(vanilla("routed"), "vanillaJoin", "routed")));
		Path forge = jar(directory, "forge.jar", Map.of(OWNER,
				gameClass(withBlock(vanilla("otherRouted"), answerBlock(5)), "vanillaJoin", "otherRouted")));
		Path forgeRuntime = jar(directory, "forge-runtime.jar", Map.of(FORGE, probes(), PROBE_EVENT, event()));
		Path neoRuntime = jar(directory, "neo-runtime.jar", Map.of(NEO, AdditiveMethodMergerTest.hookClass(NEO)));
		Path merged = directory.resolve("merged.jar"), report = directory.resolve("report.txt");
		new MergedBaseBuilder(Set.of()).run(vanilla, forge, neo, merged, report, forgeRuntime, neoRuntime);
		String text = Files.readString(report);
		assertTrue(text.contains(OWNER + "#describe" + DESCRIBE + " ACCEPTED leading hook block after a shared vanilla preamble"), text);
		assertFalse(text.contains("(forge hook lost)"), text);
		byte[] bytes;
		try (ZipFile zip = new ZipFile(merged.toFile())) {
			bytes = zip.getInputStream(zip.getEntry(OWNER + ".class")).readAllBytes();
		}
		Object game = instance(bytes);
		assertEquals("base:7", describe(game, 7));
		assertEquals(List.of("other:answer 7 21", "base:routed 7 21"), OBSERVED);
		OBSERVED.clear();
		answer = "vetoed";
		assertEquals("vetoed", describe(game, 7));
		assertEquals(List.of("other:answer 7 21"), OBSERVED);
	}

	private static Path jar(Path directory, String name, Map<String, byte[]> classes) throws Exception {
		Path path = directory.resolve(name);
		try (ZipOutputStream zip = new ZipOutputStream(Files.newOutputStream(path))) {
			for (Map.Entry<String, byte[]> entry : classes.entrySet()) {
				zip.putNextEntry(new ZipEntry(entry.getKey() + ".class"));
				zip.write(entry.getValue());
				zip.closeEntry();
			}
		}
		return path;
	}

	@Test
	void theProductionContextReadsEventsFromTheHookAndMatchesCounterpartsByNestedName() {
		MethodNode hook = new MethodNode(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC, "answer", JOIN, null, null);
		hook.instructions.add(new TypeInsnNode(Opcodes.NEW, PROBE_EVENT));
		hook.instructions.add(new InsnNode(Opcodes.POP));
		hook.instructions.add(new TypeInsnNode(Opcodes.NEW, "java/lang/Object"));
		hook.instructions.add(new InsnNode(Opcodes.POP));
		hook.instructions.add(new InsnNode(Opcodes.ACONST_NULL));
		hook.instructions.add(new InsnNode(Opcodes.ARETURN));
		ClassNode hooks = new ClassNode();
		hooks.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, FORGE, null, "java/lang/Object", null);
		hooks.methods.add(hook);
		ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
		hooks.accept(writer);
		Map<String, byte[]> forgeRuntime = Map.of(FORGE, writer.toByteArray());
		Map<String, byte[]> neoRuntime = Map.of("net/neoforged/neoforge/event/tick/ServerTickEvent$Pre", new byte[0],
				"net/neoforged/neoforge/event/Unrelated", new byte[0]);
		AdditiveMethodMerger.Context production = AdditiveMethodMerger.context(List.of(forgeRuntime, neoRuntime), Set.of());

		MethodInsnNode call = new MethodInsnNode(Opcodes.INVOKESTATIC, FORGE, "answer", JOIN, false);
		assertEquals(Set.of(PROBE_EVENT), production.constructedEvents(call), "only the family's event classes count");
		assertNull(production.constructedEvents(new MethodInsnNode(Opcodes.INVOKESTATIC, FORGE, "absent", "()V", false)));
		assertFalse(production.declaresCounterpart("net/neoforged/", PROBE_EVENT));
		assertTrue(production.declaresCounterpart("net/neoforged/", "net/minecraftforge/event/TickEvent$ServerTickEvent$Pre"),
				"the same event nested under a different outer class is a counterpart");
		assertFalse(production.declaresCounterpart("net/neoforged/", "net/minecraftforge/event/TickEvent$ServerTickEvent$Post"));
		assertFalse(production.declaresCounterpart("net/minecraftforge/", "net/minecraftforge/event/TickEvent$ServerTickEvent$Pre"),
				"a family is asked about its own declarations only");
	}

