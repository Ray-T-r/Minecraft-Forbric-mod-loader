	static final AdditiveMethodMerger.Context UNCOMPENSATED = context(true, false, Set.of(PROBE_EVENT), false);

	static AdditiveMethodMerger.Context context(boolean resolves, boolean reviewed, Set<String> events, boolean counterpart) {
		return new AdditiveMethodMerger.Context() {
			@Override public boolean resolvesStatic(String owner, String name, String descriptor) {
				return resolves && (owner.equals(NEO) || owner.equals(FORGE));
			}

			@Override public boolean reviewed(MethodInsnNode alongside, MethodInsnNode restored) { return reviewed; }

			@Override public Set<String> constructedEvents(MethodInsnNode restored) { return events; }

			@Override public boolean declaresCounterpart(String familyPackage, String event) { return counterpart; }
		};
	}

	private static AdditiveMethodMerger.Result merge(MethodNode vanilla, MethodNode base, MethodNode other,
			AdditiveMethodMerger.Context context) {
		return AdditiveMethodMerger.merge(OWNER, vanilla, base, other, "net/neoforged/", "net/minecraftforge/", context);
	}

	/**
	 * {@code String describe(int value)}: {@code long wide = value * 3L; String text = String.valueOf(value);
	 * if (text.isEmpty()) return "empty"; return this.<join>(text, wide);} -- with the frames javac would emit.
	 */
	static MethodNode vanilla(String join) {
		return framed(unframed(join));
	}

	private static MethodNode unframed(String join) {
		MethodNode method = new MethodNode(Opcodes.ASM9, Opcodes.ACC_PUBLIC, "describe", DESCRIBE, null, null);
		InsnList code = method.instructions;
		code.add(new VarInsnNode(Opcodes.ILOAD, 1));
		code.add(new InsnNode(Opcodes.I2L));
		code.add(new LdcInsnNode(3L));
		code.add(new InsnNode(Opcodes.LMUL));
		code.add(new VarInsnNode(Opcodes.LSTORE, 2));
		code.add(new VarInsnNode(Opcodes.ILOAD, 1));
		code.add(new MethodInsnNode(Opcodes.INVOKESTATIC, "java/lang/String", "valueOf", "(I)Ljava/lang/String;", false));
		code.add(new VarInsnNode(Opcodes.ASTORE, 4));
		LabelNode go = new LabelNode();
		code.add(new VarInsnNode(Opcodes.ALOAD, 4));
		code.add(new MethodInsnNode(Opcodes.INVOKEVIRTUAL, "java/lang/String", "isEmpty", "()Z", false));
		code.add(new JumpInsnNode(Opcodes.IFEQ, go));
		code.add(new LdcInsnNode("empty"));
		code.add(new InsnNode(Opcodes.ARETURN));
		code.add(go);
		code.add(new VarInsnNode(Opcodes.ALOAD, 0));
		code.add(new VarInsnNode(Opcodes.ALOAD, 4));
		code.add(new VarInsnNode(Opcodes.LLOAD, 2));
		code.add(new MethodInsnNode(Opcodes.INVOKEVIRTUAL, OWNER, join, JOIN, false));
		code.add(new InsnNode(Opcodes.ARETURN));
		return method;
	}

	/** {@code String answer = Probe.answer(text, wide); if (answer != null) return answer;} through {@code slot}. */
	static InsnList answerBlock(int slot) {
		InsnList block = new InsnList();
		LabelNode resume = new LabelNode();
		block.add(new VarInsnNode(Opcodes.ALOAD, 4));
		block.add(new VarInsnNode(Opcodes.LLOAD, 2));
		block.add(new MethodInsnNode(Opcodes.INVOKESTATIC, FORGE, "answer", JOIN, false));
		block.add(new VarInsnNode(Opcodes.ASTORE, slot));
		block.add(new VarInsnNode(Opcodes.ALOAD, slot));
		block.add(new JumpInsnNode(Opcodes.IFNULL, resume));
		block.add(new VarInsnNode(Opcodes.ALOAD, slot));
		block.add(new InsnNode(Opcodes.ARETURN));
		block.add(resume);
		return block;
	}

	/** {@code if (!Probe.allow(text)) return "refused";} */
	static InsnList vetoBlock() {
		InsnList block = new InsnList();
		LabelNode resume = new LabelNode();
		block.add(new VarInsnNode(Opcodes.ALOAD, 4));
		block.add(new MethodInsnNode(Opcodes.INVOKESTATIC, FORGE, "allow", "(Ljava/lang/String;)Z", false));
		block.add(new JumpInsnNode(Opcodes.IFNE, resume));
		block.add(new LdcInsnNode("refused"));
		block.add(new InsnNode(Opcodes.ARETURN));
		block.add(resume);
		return block;
	}

	/** {@code Probe.notice(text, wide);} */
	static InsnList observerBlock() {
		InsnList block = new InsnList();
		block.add(new VarInsnNode(Opcodes.ALOAD, 4));
		block.add(new VarInsnNode(Opcodes.LLOAD, 2));
		block.add(new MethodInsnNode(Opcodes.INVOKESTATIC, FORGE, "notice", "(Ljava/lang/String;J)V", false));
		return block;
	}

	private static MethodNode withBlock(MethodNode method, InsnList block) {
		return framed(withBlockUnframed(method, block));
	}

	/** The block right after the preamble, in a copy without frames so a case can change it before framing. */
	private static MethodNode withBlockUnframed(MethodNode method, InsnList block) {
		MethodNode copy = unframedCopy(method);
		copy.instructions.insert(executable(copy).get(PREAMBLE - 1), block);
		return copy;
	}

	private static MethodNode unframedCopy(MethodNode method) {
		MethodNode copy = new MethodNode(Opcodes.ASM9, method.access, method.name, method.desc, method.signature, null);
		method.accept(copy);
		for (AbstractInsnNode instruction : copy.instructions.toArray()) if (instruction instanceof FrameNode) copy.instructions.remove(instruction);
		return copy;
	}

	/** The method as a compiler would emit it: real compressed frames, read back from a class file. */
	static MethodNode framed(MethodNode method) {
		ClassNode holder = new ClassNode();
		holder.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, OWNER, null, "java/lang/Object", null);
		holder.methods.add(unframedCopy(method));
		ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_FRAMES | ClassWriter.COMPUTE_MAXS);
		holder.accept(writer);
		ClassNode read = new ClassNode();
		new ClassReader(writer.toByteArray()).accept(read, 0);
		return read.methods.get(0);
	}

	private static byte[] holder(MethodNode method) {
		ClassNode holder = new ClassNode();
		holder.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, OWNER, null, "java/lang/Object", null);
		MethodNode copy = new MethodNode(Opcodes.ASM9, method.access, method.name, method.desc, method.signature, null);
		method.accept(copy);
		holder.methods.add(copy);
		ClassWriter writer = new ClassWriter(0);
		holder.accept(writer);
		return writer.toByteArray();
	}

	/** Defines the game class with the composed method, written as the builder writes it, and makes one. */
	private static Object instance(MethodNode composed) throws Exception {
		return instance(gameClass(composed, "vanillaJoin", "routed", "otherRouted"));
	}

	private static Object instance(byte[] gameClass) throws Exception {
		Loader loader = new Loader();
		loader.define(PROBE_EVENT, event());
		loader.define(FORGE, probes());
		return loader.define(OWNER, gameClass).getConstructor().newInstance();
	}

	/**
	 * The game class: a constructor, {@code describe} and the named members, each forwarding to this test's recorder.
	 * Written with COMPUTE_MAXS only, like MergedBaseBuilder: the frames are the method's own, and the verifier
	 * judges them.
	 */
	private static byte[] gameClass(MethodNode describe, String... members) {
		ClassNode game = new ClassNode();
		game.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, OWNER, null, "java/lang/Object", null);
		game.methods.add(constructor());
		game.methods.add(describe);
		for (String member : members) {
			MethodNode delegate = new MethodNode(Opcodes.ACC_PUBLIC, member, JOIN, null, null);
			delegate.instructions.add(new VarInsnNode(Opcodes.ALOAD, 1));
			delegate.instructions.add(new VarInsnNode(Opcodes.LLOAD, 2));
			delegate.instructions.add(new MethodInsnNode(Opcodes.INVOKESTATIC, RECORDER, member, JOIN, false));
			delegate.instructions.add(new InsnNode(Opcodes.ARETURN));
			game.methods.add(delegate);
		}
		ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
		game.accept(writer);
		return writer.toByteArray();
	}

	private static MethodNode constructor() {
		MethodNode init = new MethodNode(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null);
		init.instructions.add(new VarInsnNode(Opcodes.ALOAD, 0));
		init.instructions.add(new MethodInsnNode(Opcodes.INVOKESPECIAL, "java/lang/Object", "<init>", "()V", false));
		init.instructions.add(new InsnNode(Opcodes.RETURN));
		return init;
	}

	/** The event the other family's answer hook constructs, so a runtime jar can say what the hook posts. */
	private static byte[] event() {
		ClassNode event = new ClassNode();
		event.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, PROBE_EVENT, null, "java/lang/Object", null);
		event.methods.add(constructor());
		ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
		event.accept(writer);
		return writer.toByteArray();
	}

	private static String describe(Object example, int value) throws Exception {
		return (String) example.getClass().getMethod("describe", int.class).invoke(example, value);
	}

	/** The other family's hook owner: each hook forwards to this test's recorder of the same name. */
	private static byte[] probes() {
		ClassNode probe = new ClassNode();
		probe.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, FORGE, null, "java/lang/Object", null);
		for (String[] hook : new String[][] { { "answer", JOIN }, { "allow", "(Ljava/lang/String;)Z" },
				{ "allowValue", "(I)Z" }, { "notice", "(Ljava/lang/String;J)V" } }) {
			MethodNode method = new MethodNode(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC, hook[0], hook[1], null, null);
			if (hook[0].equals("answer")) {
				method.instructions.add(new TypeInsnNode(Opcodes.NEW, PROBE_EVENT));
				method.instructions.add(new InsnNode(Opcodes.DUP));
				method.instructions.add(new MethodInsnNode(Opcodes.INVOKESPECIAL, PROBE_EVENT, "<init>", "()V", false));
				method.instructions.add(new InsnNode(Opcodes.POP));
			}
			int slot = 0;
			for (org.objectweb.asm.Type argument : org.objectweb.asm.Type.getArgumentTypes(hook[1])) {
				method.instructions.add(new VarInsnNode(argument.getOpcode(Opcodes.ILOAD), slot));
				slot += argument.getSize();
			}
			method.instructions.add(new MethodInsnNode(Opcodes.INVOKESTATIC, RECORDER, hook[0], hook[1], false));
			method.instructions.add(new InsnNode(org.objectweb.asm.Type.getReturnType(hook[1]).getOpcode(Opcodes.IRETURN)));
			probe.methods.add(method);
		}
		ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
		probe.accept(writer);
		return writer.toByteArray();
	}

	private static final class Loader extends ClassLoader {
		Loader() { super(LeadingHookBlockTest.class.getClassLoader()); }

		Class<?> define(String name, byte[] bytes) { return defineClass(name.replace('/', '.'), bytes, 0, bytes.length); }
	}

	private static List<AbstractInsnNode> executable(MethodNode method) {
		return AdditiveMethodMergerTest.executable(method);
	}

	private static List<String> calls(MethodNode method) {
		List<String> out = new ArrayList<>();
		for (AbstractInsnNode instruction : method.instructions) {
			if (instruction instanceof MethodInsnNode call) out.add(call.owner + "." + call.name);
		}
		return out;
	}
