	/** {@code <head> | <kind> | <ecosystems>[ | <exit>]} of every pair in {@code rows}, one per pair, kind and ecosystems. */
	static Set<String> pairs(List<String> rows) {
		Set<String> pairs = new TreeSet<>();
		for (String row : rows) {
			int colon = row.indexOf(" : "), bar = row.indexOf(" | ");
			pairs.add(row.substring(0, colon) + row.substring(bar));
		}
		return pairs;
	}

	static final String TOOLTIP = "(Lnet/minecraft/world/item/Item$TooltipContext;Lnet/minecraft/world/item/component/TooltipDisplay;"
			+ "Lnet/minecraft/world/entity/player/Player;Lnet/minecraft/world/item/TooltipFlag;Ljava/util/function/Consumer;)V";

	private static List<String> shipped() throws Exception {
		List<String> shipped = new ArrayList<>();
		try (InputStream in = CarrierRenames.class.getResourceAsStream(CarrierRenames.TABLE)) {
			assertNotNull(in, CarrierRenames.TABLE + " is missing");
			for (String line : new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\n")) {
				if (!line.isBlank() && !line.startsWith("#")) shipped.add(line.trim());
			}
		}
		return shipped;
	}

	/** Every row the staged jars support, as the census writes it. */
	static TreeSet<String> derive() throws Exception {
		for (Path jar : List.of(MERGED, VANILLA, FORGE, NEOFORGE)) {
			// MinecraftForge's merge input is the launcher library's copy where the staged one is not the merge's build.
			Fixture kind = jar == VANILLA || jar == FORGE && FORGE.startsWith(TestFixtures.minecraftDir()) ? Fixture.MC_LIBRARIES : Fixture.STAGED;
			TestFixtures.require(kind, Files.isRegularFile(jar), jar + " required");
		}
		Map<Ecosystem, ZipFile> references = new LinkedHashMap<>();
		references.put(Ecosystem.FABRIC, new ZipFile(VANILLA.toFile()));
		references.put(Ecosystem.FORGE, new ZipFile(FORGE.toFile()));
		references.put(Ecosystem.NEOFORGE, new ZipFile(NEOFORGE.toFile()));
		TreeMap<String, Set<Ecosystem>> derived = new TreeMap<>();
		Set<String> lefts = new TreeSet<>(), uncalled = new TreeSet<>();
		try (ZipFile zip = new ZipFile(MERGED.toFile())) {
			for (ZipEntry entry : Collections.list(zip.entries())) {
				if (!entry.getName().endsWith(".class")) continue;
				ClassNode merged = read(zip, entry.getName());
				Map<MethodNode, Map<String, Integer>> members = new HashMap<>();
				for (Map.Entry<Ecosystem, ZipFile> reference : references.entrySet()) {
					ClassNode original = read(reference.getValue(), entry.getName());
					if (original == null) continue;
					for (Pair pair : pairs(merged, original, members, renamed -> calledInNest(zip, merged, renamed))) {
						Map<String, Integer> before = members(CarrierHelpers.declared(original, pair.method().name, pair.method().desc));
						String head = merged.name + "#" + pair.method().name + pair.method().desc + " -> " + pair.renamed().name + pair.renamed().desc;
						CarrierRenames.Kind kind = kind(members.get(pair.renamed()), before);
						boolean called = CarrierRenames.called(merged, pair.renamed());
						boolean left = called && kind == CarrierRenames.Kind.PIECE && CarrierRenames.returnsLefts(merged, pair.method(), pair.renamed());
						for (String member : moved(members.get(pair.renamed()), before, members.get(pair.method()))) {
							String key = head + " : " + member + " x" + before.get(member) + " | " + kind.name();
							derived.computeIfAbsent(key, k -> EnumSet.noneOf(Ecosystem.class)).add(reference.getKey());
							if (left) lefts.add(key);
							if (!called) uncalled.add(key);
						}
					}
				}
			}
		} finally {
			for (ZipFile reference : references.values()) reference.close();
		}
		TreeSet<String> rows = new TreeSet<>();
		derived.forEach((head, ecosystems) -> rows.add(head + " | " + String.join(",", ecosystems.stream().sorted().map(Enum::name).toList())
				+ (lefts.contains(head) ? " | " + CarrierRenames.Exit.LEFT.name() : "")
				+ (uncalled.contains(head) ? " | " + CarrierRenames.UNCALLED : "")));
		return rows;
	}

	/** RENAME when {@code renamed} makes every call and field access of the reference's method as often, else PIECE. */
	static CarrierRenames.Kind kind(Map<String, Integer> renamed, Map<String, Integer> before) {
		for (Map.Entry<String, Integer> member : before.entrySet()) {
			if (renamed.getOrDefault(member.getKey(), 0) < member.getValue()) return CarrierRenames.Kind.PIECE;
		}
		return CarrierRenames.Kind.RENAME;
	}

	/** The calls and field accesses that moved: the reference's method makes them, the merged one less often, {@code renamed} too. */
	static Set<String> moved(Map<String, Integer> renamed, Map<String, Integer> before, Map<String, Integer> mergedMethod) {
		Set<String> moved = new TreeSet<>();
		for (Map.Entry<String, Integer> member : before.entrySet()) {
			if (renamed.getOrDefault(member.getKey(), 0) > 0 && mergedMethod.getOrDefault(member.getKey(), 0) < member.getValue()) {
				moved.add(member.getKey());
			}
		}
		return moved;
	}

	record Pair(MethodNode method, MethodNode renamed) {
	}

	/**
	 * The (method, renamed) pairs of {@code merged} against one reference class: {@code renamed} is a same-shaped method
	 * the reference does not declare, called by the merged class, and made of the reference's {@code method}
	 * ({@link #madeOf}). Then the ambiguous are dropped, since a move along any of them would be a guess: a renamed
	 * method made of two of the reference's methods (lambdas the carrier renumbered, each a line of the same few calls);
	 * two renamed methods of one method that make exactly the same calls (copies); and, of several renamed methods of
	 * one method, any the merged method does not call itself — the pieces of a split are what it dispatches to.
	 */
	static List<Pair> pairs(ClassNode merged, ClassNode original, Map<MethodNode, Map<String, Integer>> members,
			java.util.function.Predicate<MethodNode> calledInNest) {
		List<Pair> found = new ArrayList<>(), dead = new ArrayList<>();
		for (MethodNode renamed : merged.methods) {
			if (!bodied(renamed) || CarrierHelpers.declared(original, renamed.name, renamed.desc) != null) continue;
			boolean called = CarrierRenames.called(merged, renamed);
			// Dead only where nothing else can call it: a private method no other member of its nest calls either.
			// keyReleased or a public static helper may well be called from another class, or virtually.
			if (!called && ((renamed.access & Opcodes.ACC_PRIVATE) == 0 || calledInNest.test(renamed))) continue;
			for (MethodNode method : merged.methods) {
				if (method == renamed || !bodied(method) || !method.desc.equals(renamed.desc)
						|| ((method.access ^ renamed.access) & Opcodes.ACC_STATIC) != 0) continue;
				MethodNode before = CarrierHelpers.declared(original, method.name, method.desc);
				if (before == null || !bodied(before)) continue;
				if (madeOf(members.computeIfAbsent(renamed, CarrierRenameCensusTest::members), members(before),
						members.computeIfAbsent(method, CarrierRenameCensusTest::members))) {
					(called ? found : dead).add(new Pair(method, renamed));
				}
			}
		}
		List<Pair> kept = unambiguous(found, found, members);
		Map<MethodNode, Integer> homes = new HashMap<>();
		for (Pair pair : kept) homes.merge(pair.method(), 1, Integer::sum);
		kept.removeIf(pair -> homes.get(pair.method()) > 1 && !CarrierRenames.calls(merged, pair.method(), pair.renamed()));
		// A body the carrier renamed and nothing calls: kept apart, so the rules above judge the called ones exactly as
		// before. One per method, and none that copies a called one or another dead one: which would be a guess.
		List<Pair> keptDead = unambiguous(dead, java.util.stream.Stream.concat(found.stream(), dead.stream()).toList(), members);
		Map<MethodNode, Integer> deadHomes = new HashMap<>();
		for (Pair pair : keptDead) deadHomes.merge(pair.method(), 1, Integer::sum);
		keptDead.removeIf(pair -> deadHomes.get(pair.method()) > 1);
		kept.addAll(keptDead);
		return kept;
	}

	/** Whether a class nested with {@code merged} (its nest host or a nest member) calls its method {@code renamed}. */
	private static boolean calledInNest(ZipFile zip, ClassNode merged, MethodNode renamed) {
		Set<String> nest = new TreeSet<>();
		if (merged.nestHostClass != null) nest.add(merged.nestHostClass);
		if (merged.nestMembers != null) nest.addAll(merged.nestMembers);
		for (String name : nest) {
			if (name.equals(merged.name)) continue;
			try {
				ClassNode other = read(zip, name + ".class");
				if (other != null && other.methods != null) {
					for (MethodNode method : other.methods) {
						if (method.instructions == null) continue;
						for (AbstractInsnNode insn : method.instructions) {
							if (insn instanceof org.objectweb.asm.tree.MethodInsnNode call && call.owner.equals(merged.name)
									&& call.name.equals(renamed.name) && call.desc.equals(renamed.desc)) return true;
							if (insn instanceof org.objectweb.asm.tree.InvokeDynamicInsnNode indy) {
								for (Object arg : indy.bsmArgs) {
									if (arg instanceof org.objectweb.asm.Handle h && h.getOwner().equals(merged.name)
											&& h.getName().equals(renamed.name) && h.getDesc().equals(renamed.desc)) return true;
								}
							}
						}
					}
				}
			} catch (Exception unreadable) {
				return true;
			}
		}
		return false;
	}

	/**
	 * The pairs of {@code pairs} whose renamed method is made of one method only and copies no other renamed method of it
	 * among {@code all}.
	 */
	private static List<Pair> unambiguous(List<Pair> pairs, List<Pair> all, Map<MethodNode, Map<String, Integer>> members) {
		Map<MethodNode, Integer> origins = new HashMap<>();
		for (Pair pair : all) origins.merge(pair.renamed(), 1, Integer::sum);
		List<Pair> kept = new ArrayList<>();
		for (Pair pair : pairs) {
			if (origins.get(pair.renamed()) != 1) continue;
			boolean copy = false;
			for (Pair other : all) {
				if (other.renamed() != pair.renamed() && other.method() == pair.method()
						&& members.get(other.renamed()).equals(members.get(pair.renamed()))) copy = true;
			}
			if (!copy) kept.add(pair);
		}
		return kept;
	}

	/**
	 * Whether {@code renamed} is made of the reference's {@code before}: of the calls and field accesses of whichever of
	 * the two makes fewer, at least half are the other's too (a whole body renamed, or one piece of a split), at least
	 * two of them (one shared call is a coincidence, not a body), and some of those the merged method no longer makes
	 * (the body left it).
	 */
	static boolean madeOf(Map<String, Integer> renamed, Map<String, Integer> before, Map<String, Integer> mergedMethod) {
		int smaller = Math.min(total(renamed), total(before));
		if (smaller == 0) return false;
		int shared = 0, left = 0;
		for (Map.Entry<String, Integer> member : renamed.entrySet()) {
			int both = Math.min(member.getValue(), before.getOrDefault(member.getKey(), 0));
			shared += both;
			left += Math.max(0, both - mergedMethod.getOrDefault(member.getKey(), 0));
		}
		return shared >= 2 && 2 * shared >= smaller && left > 0;
	}

	private static int total(Map<String, Integer> members) {
		int total = 0;
		for (int count : members.values()) total += count;
		return total;
	}

	/** {@code method}'s calls and field accesses, with how often it makes each. */
	static Map<String, Integer> members(MethodNode method) {
		Map<String, Integer> out = new HashMap<>();
		for (AbstractInsnNode insn : method.instructions) {
			String member = CarrierHelpers.member(insn);
			if (member != null) out.merge(member, 1, Integer::sum);
		}
		return out;
	}

	private static boolean bodied(MethodNode method) {
		return !method.name.startsWith("<") && (method.access & Opcodes.ACC_BRIDGE) == 0 && method.instructions != null
				&& method.instructions.size() > 0;
	}

	private static ClassNode read(ZipFile zip, String name) throws Exception {
		ZipEntry entry = zip.getEntry(name);
		if (entry == null) return null;
		try (InputStream in = zip.getInputStream(entry)) {
			ClassNode node = new ClassNode();
			new ClassReader(in.readAllBytes()).accept(node, ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);
			return node;
		}
	}
