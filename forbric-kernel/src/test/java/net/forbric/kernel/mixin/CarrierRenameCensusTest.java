		String tooltip = "net/minecraft/world/item/ItemStack#addDetailsToTooltip" + TOOLTIP;
		assertTrue(pairs.contains(tooltip + " -> addDetailsToTooltipTail" + TOOLTIP + " | PIECE | FABRIC,FORGE"));
		assertTrue(pairs.contains("net/minecraft/server/level/ServerPlayer#startSleepInBed(Lnet/minecraft/core/BlockPos;)"
				+ "Lcom/mojang/datafixers/util/Either; -> lambda$startSleepInBed$0(Lnet/minecraft/core/BlockPos;)"
				+ "Lcom/mojang/datafixers/util/Either; | PIECE | FABRIC,FORGE | LEFT"), "super.startSleepInBed stayed in the method");
		String configuration = "net/minecraft/server/network/ServerConfigurationPacketListenerImpl#startConfiguration()V -> runConfiguration()V";
		assertTrue(pairs.contains(configuration + " | RENAME | FABRIC"), "called from handlePong, not from the method itself");
		assertTrue(pairs.contains(configuration + " | PIECE | FORGE"), "MinecraftForge's own startConfiguration does more than NeoForge's body");
		String screen = "(Lnet/minecraft/client/gui/GuiGraphicsExtractor;IIIIIFFFLnet/minecraft/world/entity/LivingEntity;)V";
